// SYNC. The Mot Dang auto-doodler (mot-dang/assets/front: skyline.js, doodler.js, doodler-*.js) as one
// anidoodle module, src/canvas-core/mddoodler.gen.ts, so a film draws its scenes inside the contract:
//   Date.now()   -> __noClock()  (throws: every drawing here is handed its `now`)
//   new Date(ms) -> __utc(ms)    (the UTC getters, from arithmetic)
//   window, document             -> local stand-ins; a canvas the doodler asks for is an env surface
// Re-run whenever the doodler changes (ani.mjs runs it when a source is newer than the module).
//   node tools/md/sync.mjs [--front <mot-dang/assets/front>]
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const MOTDANG = resolve(process.env.MOTDANG ?? `${process.env.HOME}/Developer/claude code projects/mot-dang`);
export const OUT = "src/canvas-core/mddoodler.gen.ts";

export const sources = (front = join(MOTDANG, "assets/front")) =>
  ["skyline.js", "doodler.js", ...readdirSync(front).filter((n) => /^doodler-.+\.js$/.test(n) && !/^doodler-ani-/.test(n)).sort(), ...readdirSync(front).filter((n) => /^doodler-ani-.+\.js$/.test(n)).sort()]
    .map((n) => join(front, n)).filter((p) => existsSync(p));

export const stale = (front) => !existsSync(OUT) || sources(front).some((p) => statSync(p).mtimeMs > statSync(OUT).mtimeMs);

const ridge = () => {
  const built = join(MOTDANG, "docs/front/ridge.json");
  if (existsSync(built)) return JSON.parse(readFileSync(built, "utf8"));
  const p = JSON.parse(readFileSync(join(MOTDANG, "data/terrain_profile.json"), "utf8"));
  return Object.fromEntries(["lat", "lon_a", "lon_b", "step", "tick", "ele", "read"].map((k) => [k, p[k]]));
};

const UTC = `function __utc(ms) {
  const d = Math.floor(ms / 864e5), s = ms - d * 864e5, z = d + 719468, era = Math.floor(z / 146097), doe = z - era * 146097;
  const yoe = Math.floor((doe - Math.floor(doe / 1460) + Math.floor(doe / 36524) - Math.floor(doe / 146096)) / 365), doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  const mp = Math.floor((5 * doy + 2) / 153), day = doy - Math.floor((153 * mp + 2) / 5) + 1, mon = mp < 10 ? mp + 3 : mp - 9, yr = yoe + era * 400 + (mon <= 2 ? 1 : 0);
  const p2 = (n) => String(n).padStart(2, "0"), h = Math.floor(s / 36e5), mi = Math.floor(s / 6e4) % 60, se = Math.floor(s / 1e3) % 60;
  return { getTime: () => ms, getUTCFullYear: () => yr, getUTCMonth: () => mon - 1, getUTCDate: () => day, getUTCDay: () => ((d % 7) + 11) % 7, getUTCHours: () => h, getUTCMinutes: () => mi, getUTCSeconds: () => se,
    toISOString: () => yr + "-" + p2(mon) + "-" + p2(day) + "T" + p2(h) + ":" + p2(mi) + ":" + p2(se) + "." + String(Math.floor(s) % 1e3).padStart(3, "0") + "Z" };
}`;

export const sync = (front) => {
  const files = sources(front), seen = {};
  const body = files.map((p) => {
    const raw = readFileSync(p, "utf8"), name = p.slice(p.lastIndexOf("/") + 1);
    seen[name] = createHash("sha256").update(raw).digest("hex").slice(0, 12);
    const src = raw.replace(/\bDate\.now\(\)/g, "__noClock()").replace(/\bnew Date\(/g, "__utc(");
    const left = src.match(/\bDate\.now\b|\bnew Date\b|Math\.random|performance\.now|localStorage|\bfetch\s*\(|XMLHttpRequest/g);
    if (left) throw new Error(`${name}: ${[...new Set(left)].join(", ")} left after the rewrite; teach sync.mjs this one`);
    return `/* ---- ${name} ${seen[name]} */\n${src}`;
  }).join("\n");
  const ts = `// @ts-nocheck
// GENERATED by tools/md/sync.mjs from ${files.length} files of mot-dang/assets/front; edit those, then run it again.
export const SOURCES: Record<string, string> = ${JSON.stringify(seen)};
export const RIDGE = ${JSON.stringify(ridge())};
${UTC}
export const makeMDD = (surface: () => unknown) => {
  const window: any = {};
  const document = { createElement: (k: string) => (k === "canvas" ? surface() : { style: {} }), head: { appendChild() {} } };
  const __noClock = () => { throw new Error("mddoodler: a drawing asked for the clock; hand it now"); };
${body}
  return { D: window.MDDOODLER, SKY: window.MDSKY };
};
`;
  writeFileSync(OUT, ts);
  return { files: files.length, bytes: ts.length };
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const i = process.argv.indexOf("--front"), r = sync(i > 0 ? resolve(process.argv[i + 1]) : undefined);
  console.log(`${OUT}: ${r.files} doodler files, ${(r.bytes / 1024).toFixed(0)} KB`);
}
